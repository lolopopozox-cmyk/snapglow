#!/usr/bin/env python3
"""
Snap Glow — SEO toolkit (no third-party dependencies).

Usage:
    python scripts/seo.py site --base https://snapglow-nine.vercel.app
        Regenerates public/sitemap.xml and public/robots.txt for the site.

    python scripts/seo.py audit --base https://snapglow-nine.vercel.app
        Audits index.html meta tags (title/description lengths, canonical,
        Open Graph, Twitter card, JSON-LD) and prints pass/fail per check.

    python scripts/seo.py ping --base https://snapglow-nine.vercel.app
        Best-effort sitemap ping to Google/Bing (needs internet; failures
        are reported, not fatal).

The sitemap contains STATIC PUBLIC ROUTES only — dynamic pages
(/u/:username, /cards/:id, /battles/:id, /posts/:id) carry noindex meta
tags (user content) and are intentionally excluded.
"""
from __future__ import annotations

import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parent.parent
PUBLIC = ROOT / "public"

# (path, changefreq, priority)
STATIC_ROUTES: list[tuple[str, str, str]] = [
    ("/", "daily", "1.0"),
    ("/discover", "daily", "0.9"),
    ("/feed", "daily", "0.9"),
    ("/trending", "daily", "0.8"),
    ("/battles", "daily", "0.8"),
    ("/leaderboards/daily", "daily", "0.8"),
    ("/leaderboards/weekly", "daily", "0.8"),
    ("/leaderboards/most-liked", "daily", "0.7"),
    ("/leaderboards/most-wins", "daily", "0.7"),
    ("/leaderboards/win-streaks", "daily", "0.7"),
    ("/leaderboards/profile-likes", "daily", "0.7"),
    ("/leaderboards/all-time", "daily", "0.7"),
    ("/leaderboards/rising", "daily", "0.7"),
    ("/leaderboards/top-voters", "daily", "0.7"),
    ("/leaderboards/recent-winners", "daily", "0.7"),
    ("/hall-of-fame", "weekly", "0.6"),
    ("/search", "weekly", "0.4"),
    ("/contact", "monthly", "0.5"),
    ("/privacy", "yearly", "0.3"),
    ("/terms", "yearly", "0.3"),
    ("/guidelines", "yearly", "0.3"),
]

DISALLOWED = ["/signin", "/dashboard", "/admin", "/admin/login", "/create"]


def build_sitemap(base: str) -> str:
    ns = "http://www.sitemaps.org/schemas/sitemap/0.9"
    ET.register_namespace("", ns)
    urlset = ET.Element(f"{{{ns}}}urlset")
    for path, freq, prio in STATIC_ROUTES:
        url = ET.SubElement(urlset, f"{{{ns}}}url")
        ET.SubElement(url, f"{{{ns}}}loc").text = base + path
        ET.SubElement(url, f"{{{ns}}}changefreq").text = freq
        ET.SubElement(url, f"{{{ns}}}priority").text = prio
    ET.indent(urlset, space="  ")
    return ET.tostring(urlset, encoding="unicode", xml_declaration=False) + "\n"


def build_robots(base: str) -> str:
    lines = [
        "# Snap Glow robots.txt — generated by scripts/seo.py",
        "# Public pages are crawlable. Private/demo-auth/admin surfaces are",
        "# additionally protected with <meta name=\"robots\" content=\"noindex\">.",
        "# robots.txt is NOT access control — it is only a crawling hint.",
        "",
        "User-agent: *",
        "Allow: /",
        "",
    ]
    lines += [f"Disallow: {d}" for d in DISALLOWED]
    lines += ["", f"Sitemap: {base}/sitemap.xml", ""]
    return "\n".join(lines)


def cmd_site(base: str) -> int:
    sitemap = PUBLIC / "sitemap.xml"
    robots = PUBLIC / "robots.txt"
    header = '<?xml version="1.0" encoding="UTF-8"?>\n'
    sitemap.write_text(header + build_sitemap(base), encoding="utf-8")
    robots.write_text(build_robots(base), encoding="utf-8")
    print(f"✅ wrote {sitemap.relative_to(ROOT)} ({len(STATIC_ROUTES)} URLs)")
    print(f"✅ wrote {robots.relative_to(ROOT)} ({len(DISALLOWED)} disallows)")
    return 0


def cmd_audit(base: str) -> int:
    html_path = ROOT / "index.html"
    html = html_path.read_text(encoding="utf-8")
    checks: list[tuple[bool, str]] = []

    def meta(name: str, attr: str = "name") -> str:
        token = f'{attr}="{name}"'
        i = html.find(token)
        if i == -1:
            return ""
        start = html.find("content=", i)
        if start == -1:
            return ""
        quote = html[start + 8]
        end = html.find(quote, start + 9)
        return html[start + 9 : end]

    title = html.split("<title>", 1)[1].split("</title>", 1)[0] if "<title>" in html else ""
    desc = meta("description")
    keywords = meta("keywords")
    canonical = html.split('<link rel="canonical" href="', 1)[1].split('"', 1)[0] if 'rel="canonical"' in html else ""
    og_title = meta("og:title", "property")
    og_desc = meta("og:description", "property")
    og_image = meta("og:image", "property")
    og_url = meta("og:url", "property")
    tw_card = meta("twitter:card")
    viewport = meta("viewport")

    checks.append((30 <= len(title) <= 65, f"title length {len(title)} (target 30–65): “{title}”"))
    checks.append((70 <= len(desc) <= 165, f"description length {len(desc)} (target 70–165)"))
    checks.append((len(keywords) > 40, f"keywords present ({len(keywords)} chars)"))
    checks.append((canonical.startswith("https://"), f"canonical → {canonical or 'MISSING'}"))
    checks.append((base.rstrip('/') in canonical, "canonical matches --base"))
    checks.append((bool(og_title and og_desc), "Open Graph title + description"))
    checks.append((og_image.startswith("https://"), f"og:image absolute URL ({og_image[:60]}…)"))
    checks.append((bool(og_url), "og:url present"))
    checks.append((tw_card == "summary_large_image", f"twitter:card = {tw_card}"))
    checks.append((bool(viewport), "viewport meta present"))
    checks.append(("application/ld+json" in html, "JSON-LD structured data present"))
    checks.append((html.count('application/ld+json') >= 2, "JSON-LD WebSite + Organization"))

    # sitemap + robots consistency
    sm = (PUBLIC / "sitemap.xml").read_text(encoding="utf-8") if (PUBLIC / "sitemap.xml").exists() else ""
    checks.append((f"{base}/" in sm, "sitemap contains site root"))
    rb = (PUBLIC / "robots.txt").read_text(encoding="utf-8") if (PUBLIC / "robots.txt").exists() else ""
    checks.append((f"Sitemap: {base}/sitemap.xml" in rb, "robots.txt points to sitemap"))
    checks.append(("Disallow: /admin" in rb, "robots.txt disallows /admin"))

    failed = 0
    for ok, label in checks:
        mark = "✅" if ok else "❌"
        if not ok:
            failed += 1
        print(f"{mark} {label}")
    print(f"\n{'PASS' if failed == 0 else f'FAIL — {failed} check(s)'} ({len(checks)} checks)")
    return 1 if failed else 0


def cmd_ping(base: str) -> int:
    sitemap = urllib.parse.quote(f"{base}/sitemap.xml", safe=":/")
    targets = [
        f"https://www.google.com/ping?sitemap={sitemap}",
        f"https://www.bing.com/ping?sitemap={sitemap}",
    ]
    for t in targets:
        try:
            req = urllib.request.Request(t, method="GET", headers={"User-Agent": "snapglow-seo/1.0"})
            with urllib.request.urlopen(req, timeout=15) as resp:
                print(f"✅ pinged {t.split('?')[0]} → HTTP {resp.status}")
        except Exception as exc:  # noqa: BLE001 — report, don't crash
            print(f"⚠️  ping failed for {t.split('?')[0]}: {exc}")
    print("\nNote: Google deprecated sitemap pings in 2023 — submitting once in")
    print("Search Console (https://search.google.com/search-console) is the reliable path.")
    return 0


def main(argv: list[str]) -> int:
    if len(argv) < 2 or argv[1] not in {"site", "audit", "ping"}:
        print(__doc__)
        return 2
    base = "https://snapglow-nine.vercel.app"
    if "--base" in argv:
        base = argv[argv.index("--base") + 1].rstrip("/")
    if argv[1] == "site":
        return cmd_site(base)
    if argv[1] == "audit":
        return cmd_audit(base)
    return cmd_ping(base)


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
